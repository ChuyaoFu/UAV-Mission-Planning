#!/usr/bin/env python3
"""Gazebo replica of the REAL maze of 2026-11-08 (organisers changed it vs COURSE_MAP), from mission-core's survey
prior mission/course_prior.real_maze_20261108.json (walls measured in BOTH hand-carried flights, start frame f / l).

  python3 make_realmaze.py VARIANT [--prior /compat/profile/mission/course_prior.real_maze_20261108.json]   (container)
      VARIANT = base | w591    (w591 = + the uncertain wall_l-5.91, seen in one flight, 0.35 m outside the official
                                east net -> beyond the replica's net)
      -> /compat/realmaze/<VARIANT>/replica  (layout.py + REALMAZE block, world/), flown with --replica

Built: the official barrier + its measured east parts (barrier_east_w l -4.1..-4.3, barrier_east_e l -5.15..-5.566;
the opening l -4.30..-5.15 is where the tunnel passes the barrier line), board_f1.14, diag_board, wall_f1.45,
wall_l-4.21, wall_l-5.375 (+ wall_l-5.91 in w591); tunnel entry centre (f -1.28, l -4.82), axis 180 deg (south),
official length 1.524 m, centre height = up 0.71 + 0.05 (base_link rest) = 0.76 m, official hoop radius 0.55
(the detector's ~0.78 is not used). Dropped: W1, W2, W3, C1 and their cinder blocks. Kept as official / unverified:
C2_north, W4, window, pad, Gate B, boulders, cage. Launch = the official launch (the measured barrier matches it).
Skins: plywood for the measured walls (look unknown). No floor tape.
"""
import argparse, importlib.util, json, math, os, shutil, subprocess, sys
from pathlib import Path

FT = 0.3048
CONFIRMED = ('barrier_east_w', 'barrier_east_e', 'board_f1.14', 'diag_board', 'wall_f1.45', 'wall_l-4.21', 'wall_l-5.375')


def build_b(a, L, P):
    """version b (whole-loop survey): the WHOLE course from the prior, in the start frame. Cage: square, south net on
    fence.forward_min (-4.88, beyond the official net), west net on fence.left_max; side = forward span (7.01 m), so the
    east net lands at l -6.48 (real: a line at -5.83; the mission's own fence -5.566 keeps the vehicle inside). Walls: every
    prior wall (plywood, map heights) except window_board_n/_s (= the window board itself); block_* solid 0 -> 1.80 m.
    Window: board 1.5 m on the measured line, opening 0.81 x 0.67 m, centre up + 0.05. Pad, barrier, tunnel from the prior.
    No boulders (all five official positions seen free), no Gate B, no cinder blocks, no tape."""
    fz = P['fence']; S0, S1 = -fz['forward_min'], fz['left_max']                # START (a, b) = launch in cage coords
    cage = fz['forward_max'] - fz['forward_min']
    lx, ly = S1 / FT, S0 / FT                                                    # new LAUNCH_FT
    ft = lambda f, l: (round(lx - l / FT, 4), round(ly + f / FT, 4))
    walls = []
    for w in P['walls']:
        if w['name'].startswith('window_board'):
            continue
        p0 = (w['from']['forward'], min(w['from']['left'], S1 - 0.03)); p1 = (w['to']['forward'], min(w['to']['left'], S1 - 0.03))
        walls.append((w['name'], ft(*p0), ft(*p1), 'plywood', 'REAL maze b: ' + w.get('_source', '')[:60]))
    W = P['window']; th = math.radians(W['through_deg'])
    cross = (-math.sin(th), math.cos(th)); along = (math.cos(th), math.sin(th))   # map (x east, y north) of crossing / long axis
    wc = ft(W['center']['forward'], W['center']['left'])
    bar = next(w for w in P['walls'] if w['name'] == 'barrier')
    te = P['tunnel']['entry']; ax = math.radians(P['tunnel']['axis_deg']); ln = float(P['tunnel'].get('length_m', 1.524))
    ent = ft(te['forward'], te['left']); ext = ft(te['forward'] + ln * math.cos(ax), te['left'] + ln * math.sin(ax))
    pad = P['landing_target']['center']; blk_top = float(P['wall'].get('top_up', 1.80))
    root = Path(a.dst) / a.variant; rep = root / 'replica'
    if root.exists():
        shutil.rmtree(root)
    rep.mkdir(parents=True)
    for f in Path(a.src).glob('*.py'):
        shutil.copy2(f, rep / f.name)
    shutil.copytree(Path(a.src) / 'assets', rep / 'assets')
    os.symlink('/compat/profile/common', root / 'common')
    block = f'''

# ================= REAL MAZE 2026-11-08 version b - generated by ubuntu_compat/make_realmaze.py (build_b) =================
# from {a.prior}; whole course in the start frame, see make_realmaze.build_b
CAGE = {cage:.4f}
FLOOR_SIZE = CAGE + 2 * TARP
LAUNCH_FT = ({lx:.4f}, {ly:.4f})
START = (LAUNCH_FT[1] * FT, LAUNCH_FT[0] * FT)
WALLS_FT = {json.dumps(walls)}
WALLS_FT = [(n, tuple(p0), tuple(p1), sk, ro) for n, p0, p1, sk, ro in WALLS_FT]
MAZE_WALLS = [(n, ft_fl(*p0), ft_fl(*p1), skin, role) for (n, p0, p1, skin, role) in WALLS_FT]
PANELS = _panels_from_walls(WALLS_FT)
for _p in PANELS:
    if _p['wall'].startswith('block_'):
        _p.update(bottom=0.0, top={blk_top:.3f})
WINDOW_FT = dict(cx={wc[0]}, cy={wc[1]}, along=({along[0]:.5f}, {along[1]:.5f}), cross=({cross[0]:.5f}, {cross[1]:.5f}))
WINDOW.update(hole_w=0.81, hole_h=0.67, hole_c={W['center']['up'] + 0.05:.3f})
WINDOW['a'], WINDOW['b'] = ft_ab(WINDOW_FT['cx'], WINDOW_FT['cy'])
WINDOW['yaw'] = math.degrees(math.atan2(WINDOW_FT['along'][0], WINDOW_FT['along'][1]))
WINDOW['normal_ne'] = (-WINDOW_FT['cross'][1], -WINDOW_FT['cross'][0])
WALL = dict(WALL, x0={lx - min(bar['from']['left'], S1) / FT:.4f}, x1={lx - bar['to']['left'] / FT:.4f}, y={ly + bar['from']['forward'] / FT:.4f})
TUNNEL['entry_ft'], TUNNEL['exit_ft'] = {ent}, {ext}
TUNNEL['centre_h'] = {float(te['up']) + 0.05:.3f}
TUNNEL['entry_ab'] = ft_ab(*TUNNEL['entry_ft']); TUNNEL['exit_ab'] = ft_ab(*TUNNEL['exit_ft'])
_ax = np.subtract(TUNNEL['exit_ab'], TUNNEL['entry_ab']); TUNNEL['length'] = float(np.linalg.norm(_ax))
TUNNEL['axis_ab'] = tuple(float(v) for v in _ax / TUNNEL['length'])
PAD.update(n={pad['forward']:.4f}, e={-pad['left']:.4f})
TAPE_FT = []; TAPE = []
BOULDERS_FT = []; BOULDERS = []; ROCKS = BOULDERS
_BLOCKS_FT = []; CINDER_BLOCKS = []
del GATE_B_ROUTE_FT
REALMAZE_VARIANT = 'b'
'''
    with open(rep / 'layout.py', 'a') as f:
        f.write(block)
    (rep / 'realmaze.json').write_text(json.dumps(dict(variant='b', prior=a.prior, cage=cage, launch_ft=(lx, ly), walls=[w[:3] for w in walls],
                                                       tunnel=dict(entry_ft=ent, exit_ft=ext)), indent=1))
    r = subprocess.run([sys.executable, str(rep / 'build_world.py'), '--out', str(rep / 'world')], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-1500:], r.stderr[-3000:]); sys.exit(1)
    print(f'{rep}: b, cage {cage:.3f} m (south net f {fz["forward_min"]}), {len(walls)} walls, window ft {wc}, pad ({pad["forward"]}, {pad["left"]}), tunnel {ent} -> {ext}')


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('variant', choices=['base', 'w591', 'b'])
    ap.add_argument('--prior', default=None)
    ap.add_argument('--src', default='/replica'); ap.add_argument('--dst', default='/compat/realmaze')
    a = ap.parse_args()
    spec = importlib.util.spec_from_file_location('layout_src', Path(a.src) / 'layout.py')
    L = importlib.util.module_from_spec(spec); spec.loader.exec_module(L)
    a.prior = a.prior or ('/compat/profile/mission/course_prior.real_maze_20261108b.json' if a.variant == 'b'
                          else '/compat/profile/mission/course_prior.real_maze_20261108.json')
    P = json.loads(Path(a.prior).read_text())
    if a.variant == 'b':
        return build_b(a, L, P)
    lx, ly = L.LAUNCH_FT
    ft = lambda q: (round(lx - q['left'] / FT, 4), round(ly + q['forward'] / FT, 4))     # start frame -> map ft
    names = CONFIRMED + (('wall_l-5.91',) if a.variant == 'w591' else ())
    meas = [(w['name'], ft(w['from']), ft(w['to']), 'plywood', 'REAL maze 2026-11-08: ' + w.get('_source', '')[:60])
            for w in P['walls'] if w['name'] in names]
    assert len(meas) == len(names), ('walls missing in the prior', names, [m[0] for m in meas])
    keep = [w for w in L.WALLS_FT if w[0] in ('barrier', 'C2_north', 'W4')]
    walls = keep + meas
    te = P['tunnel']['entry']; ax = math.radians(P['tunnel']['axis_deg']); ln = float(P['tunnel'].get('length_m', 1.524))
    ent = ft(te); ext = ft({'forward': te['forward'] + ln * math.cos(ax), 'left': te['left'] + ln * math.sin(ax)})
    centre_h = float(te['up']) + 0.05
    blocks = [b for b in L._BLOCKS_FT if (b[0], b[1]) in ((7.2, 8.3), (7.2, 11.0), (9.9, 5.4), (2.2, 11.15), (12.6, 11.15))]
    root = Path(a.dst) / a.variant; rep = root / 'replica'
    if root.exists():
        shutil.rmtree(root)
    rep.mkdir(parents=True)
    for f in Path(a.src).glob('*.py'):
        shutil.copy2(f, rep / f.name)
    shutil.copytree(Path(a.src) / 'assets', rep / 'assets')
    os.symlink('/compat/profile/common', root / 'common')
    block = f'''

# ================= REAL MAZE 2026-11-08 ({a.variant}) - generated by ubuntu_compat/make_realmaze.py =================
# from mission/course_prior.real_maze_20261108.json (walls measured in both hand-carried flights); see the docstring.
WALLS_FT = {json.dumps(walls)}
WALLS_FT = [(n, tuple(p0), tuple(p1), sk, ro) for n, p0, p1, sk, ro in WALLS_FT]
MAZE_WALLS = [(n, ft_fl(*p0), ft_fl(*p1), skin, role) for (n, p0, p1, skin, role) in WALLS_FT]
PANELS = _panels_from_walls(WALLS_FT)
TUNNEL['entry_ft'], TUNNEL['exit_ft'] = {ent}, {ext}
TUNNEL['centre_h'] = {centre_h:.3f}
TUNNEL['entry_ab'] = ft_ab(*TUNNEL['entry_ft']); TUNNEL['exit_ab'] = ft_ab(*TUNNEL['exit_ft'])
_ax = np.subtract(TUNNEL['exit_ab'], TUNNEL['entry_ab']); TUNNEL['length'] = float(np.linalg.norm(_ax))
TUNNEL['axis_ab'] = tuple(float(v) for v in _ax / TUNNEL['length'])
_BLOCKS_FT = {json.dumps(blocks)}
CINDER_BLOCKS = [(*ft_ned(x, y)[:2], yaw) for x, y, yaw in _BLOCKS_FT]
TAPE_FT = []
TAPE = []
REALMAZE_VARIANT = '{a.variant}'
'''
    with open(rep / 'layout.py', 'a') as f:
        f.write(block)
    (rep / 'realmaze.json').write_text(json.dumps(dict(variant=a.variant, prior=a.prior, walls=[m[:3] for m in meas],
                                                       tunnel=dict(entry_ft=ent, exit_ft=ext, centre_h=centre_h)), indent=1))
    r = subprocess.run([sys.executable, str(rep / 'build_world.py'), '--out', str(rep / 'world')], capture_output=True, text=True)
    if r.returncode != 0:
        print(r.stdout[-1500:], r.stderr[-3000:]); sys.exit(1)
    print(f'{rep}: {len(meas)} measured walls + {[w[0] for w in keep]}, tunnel entry ft {ent} -> exit {ext}, centre h {centre_h:.2f} m')


if __name__ == '__main__':
    main()
